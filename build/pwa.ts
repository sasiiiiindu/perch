/**
 * Vite plugin that makes the build an installable, offline-capable app:
 * draws the icons, writes the web app manifest, links both from index.html,
 * and writes a service worker that caches every built file.
 *
 * Hand-written rather than Workbox: Perch is a handful of files, and the
 * whole caching policy fits on one screen (see serviceWorkerSource).
 */

import type { Plugin } from 'vite';
import { APPLE_TOUCH_ICON, ICONS, renderIcon } from './icons.ts';

const MANIFEST = 'manifest.webmanifest';
const SERVICE_WORKER = 'sw.js';

/** Built files the service worker caches: everything except itself and source maps. */
export function precacheFiles(fileNames: Iterable<string>): string[] {
  return [...fileNames].filter((f) => f !== SERVICE_WORKER && !f.endsWith('.map')).sort();
}

/** Files without which Perch can't start offline. The build fails if one is missing. */
const REQUIRED = [/^index\.html$/, /pitch-processor.*\.js$/, /analysis-worker.*\.js$/, /^manifest\.webmanifest$/, /^icons\/.+\.png$/];

export function missingRequired(files: readonly string[]): RegExp[] {
  return REQUIRED.filter((re) => !files.some((f) => re.test(f)));
}

/** Short, stable hash: a new set of hashed file names means a new cache. */
export function versionOf(files: readonly string[]): string {
  let h = 2166136261;
  for (const ch of files.join('\n')) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return (h >>> 0).toString(36);
}

/**
 * Cache-first for everything, the page included. Each version's files are
 * cached together, so the page and its assets always match: an online
 * reload never mixes a new index.html with an old cache.
 *
 * A new version installs in the background and takes over only once every
 * Perch tab is closed (no skipWaiting). Taking over mid-session could delete
 * a cached file the open page still needs, like the worklet it loads on Start.
 */
export function serviceWorkerSource(files: readonly string[], version: string): string {
  return `// Generated by build/pwa.ts.
const CACHE = 'perch-${version}';
const FILES = ${JSON.stringify(files)};
const scoped = (path) => new URL(path, self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES.map((f) => new Request(scoped(f), { cache: 'reload' })))),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('perch-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || !request.url.startsWith(self.registration.scope)) return;
  // Any page in scope (with ?debug, ?chorus, …) is the one index.html.
  const cached = request.mode === 'navigate'
    ? caches.match(scoped('index.html'), { cacheName: CACHE })
    : caches.match(request, { cacheName: CACHE });
  event.respondWith(cached.then((hit) => hit || fetch(request)));
});
`;
}

export function pwa(): Plugin {
  let base = '/';
  return {
    name: 'perch-pwa',
    apply: 'build',
    // After Vite's own plugins, so index.html and every chunk are already in the bundle.
    enforce: 'post',
    configResolved(config) {
      base = config.base;
    },
    transformIndexHtml() {
      return [
        { tag: 'link', attrs: { rel: 'manifest', href: `${base}${MANIFEST}` }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', href: `${base}${APPLE_TOUCH_ICON.file}` }, injectTo: 'head' },
      ];
    },
    async generateBundle(_, bundle) {
      // Files emitted here don't show up in `bundle` straight away, so they're listed by hand.
      const emitted: string[] = [];
      for (const spec of [...ICONS, APPLE_TOUCH_ICON]) {
        this.emitFile({ type: 'asset', fileName: spec.file, source: await renderIcon(spec) });
        emitted.push(spec.file);
      }
      // Loaded here, after renderIcon has given Node a Path2D (birds.ts needs it on load).
      const { COLORS } = await import('../src/scene/birds.ts');
      const manifest = {
        id: './',
        name: 'Perch',
        short_name: 'Perch',
        description: 'A calm guitar tuner: six birds on a wire, one for each string.',
        start_url: './',
        scope: './',
        display: 'standalone',
        background_color: COLORS.ground,
        theme_color: COLORS.ground,
        icons: ICONS.map((i) => ({ src: i.file, sizes: `${i.size}x${i.size}`, type: 'image/png', purpose: i.purpose })),
      };
      this.emitFile({ type: 'asset', fileName: MANIFEST, source: JSON.stringify(manifest, null, 2) });
      emitted.push(MANIFEST);

      const files = precacheFiles(new Set([...Object.keys(bundle), ...emitted]));
      const missing = missingRequired(files);
      if (missing.length) this.error(`Service worker would be missing: ${missing.join(', ')}`);
      this.emitFile({ type: 'asset', fileName: SERVICE_WORKER, source: serviceWorkerSource(files, versionOf(files)) });
    },
  };
}
